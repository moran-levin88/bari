export type Locale = 'he' | 'en'
export type TranslateFn = (key: string, vars?: Record<string, string | number>) => string

function applyVars(str: string, vars?: Record<string, string | number>): string {
  if (!vars) return str
  return Object.entries(vars).reduce((s, [k, v]) => s.replace(`{${k}}`, String(v)), str)
}

// Server- and client-safe translator factory — no React dependency.
export function createT(locale: Locale): TranslateFn {
  return (key, vars) => {
    const [section, field] = key.split('.')
    const dict = dictionaries[locale] as Record<string, Record<string, string>>
    const value = dict[section]?.[field] ?? (dictionaries.he as Record<string, Record<string, string>>)[section]?.[field] ?? key
    return applyVars(value, vars)
  }
}

